// Falls back to English when a key or a whole language isn't covered yet
// (see UI_TRANSLATED above), rather than showing a blank or a raw key.
function t(key) {
  var lang = getStoredLanguage();
  var table = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return table[key] || TRANSLATIONS.en[key] || key;
}

function getStoredLanguage() {
  try {
    return localStorage.getItem('tervexa-language') || 'en';
  } catch (err) {
    // Some browsers block storage access entirely (private mode, strict
    // privacy settings). Fall back to English rather than breaking the AI
    // request over it.
    return 'en';
  }
}

function setStoredLanguage(code) {
  try {
    localStorage.setItem('tervexa-language', code);
  } catch (err) {
    console.error('Could not save language preference:', err);
  }
}

// Walks every element carrying a translation attribute and fills it in
// for the given language. data-i18n sets the element's text;
// data-i18n-placeholder sets an input's placeholder — kept separate
// because setting textContent on an <input> does nothing.
function applyTranslations(langCode) {
  var table = TRANSLATIONS[langCode] || TRANSLATIONS.en;

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    el.textContent = table[key] || TRANSLATIONS.en[key] || el.textContent;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = table[key] || TRANSLATIONS.en[key] || el.placeholder;
  });

  document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-alt');
    el.alt = table[key] || TRANSLATIONS.en[key] || el.alt;
  });

  document.documentElement.lang = langCode;

  // Some pages rebuild bits of their own text dynamically (e.g. the fault
  // report page's title/subtitle/button change with the selected request
  // type). Let that page-specific code know the language just changed so
  // it can redraw with the new language instead of being overwritten by
  // static [data-i18n] text a moment ago, or left showing English.
  document.dispatchEvent(new CustomEvent('tervexa:languagechange', { detail: { lang: langCode } }));
}

// Resolves which language to actually show: a logged-in account's saved
// preference wins (so it matches what WhatsApp would use for the same
// account); logged out, it falls back to whatever this browser last had
// selected. meData is the already-fetched /api/me response — reusing it
// here avoids a second network round trip just for this.
function initLanguage(meData) {
  var resolved = getStoredLanguage();

  if (meData && meData.loggedIn && meData.preferredLanguage) {
    resolved = meData.preferredLanguage;
    setStoredLanguage(resolved);
  }

  var langSelector = document.getElementById('lang-selector');

  if (langSelector) {
    langSelector.value = resolved;

    langSelector.addEventListener('change', function () {
      var chosen = langSelector.value;
      setStoredLanguage(chosen);
      applyTranslations(chosen);

      // Only an already-logged-in visitor has an account to save this to;
      // a logged-out change just stays in this browser via localStorage,
      // same as before, until they sign up or log in.
      if (meData && meData.loggedIn) {
        fetch('/api/preferred-language', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ language: chosen })
        }).catch(function (err) {
          console.error('Could not save language preference to account:', err);
        });
      }
    });
  }

  applyTranslations(resolved);
}